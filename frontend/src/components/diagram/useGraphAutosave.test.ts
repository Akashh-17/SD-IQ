import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { useGraphAutosave } from "./useGraphAutosave";
import { saveGraph } from "../../services/graph.service";
import type { GraphDocument } from "./document";
vi.mock("../../services/graph.service", () => ({ saveGraph: vi.fn() }));
const graph = (x = 0): GraphDocument => ({ nodes: [{ id: "api", position: { x, y: 0 }, data: { label: "API" } }], edges: [] });
beforeEach(() => { vi.useFakeTimers(); vi.mocked(saveGraph).mockResolvedValue(undefined); });
afterEach(() => { cleanup(); vi.useRealTimers(); vi.resetAllMocks(); });
it("never saves an empty canvas before restore, and debounces edits", async () => {
    const status = vi.fn();
    const { rerender } = renderHook(({ loaded, revision, document }) => useGraphAutosave("id", document, revision, loaded, status), { initialProps: { loaded: false, revision: 0, document: graph() } });
    await act(() => vi.advanceTimersByTimeAsync(1000));
    expect(saveGraph).not.toHaveBeenCalled();
    rerender({ loaded: true, revision: 0, document: graph() });
    await act(() => vi.advanceTimersByTimeAsync(1000));
    expect(saveGraph).not.toHaveBeenCalled();
    rerender({ loaded: true, revision: 1, document: graph(16) });
    await act(() => vi.advanceTimersByTimeAsync(250));
    rerender({ loaded: true, revision: 2, document: graph(32) });
    await act(() => vi.advanceTimersByTimeAsync(499));
    expect(saveGraph).not.toHaveBeenCalled();
    await act(() => vi.advanceTimersByTimeAsync(1));
    expect(saveGraph).toHaveBeenCalledExactlyOnceWith("id", graph(32));
    expect(status).toHaveBeenLastCalledWith("saved");
});
it("serializes saves and keeps newer edits dirty until their own request finishes", async () => {
    let first!: () => void, second!: () => void;
    vi.mocked(saveGraph).mockImplementationOnce(() => new Promise(resolve => { first = () => resolve(); })).mockImplementationOnce(() => new Promise(resolve => { second = () => resolve(); }));
    const status = vi.fn();
    const { rerender, result } = renderHook(({ revision }) => useGraphAutosave("id", graph(revision * 16), revision, true, status), { initialProps: { revision: 1 } });
    await act(() => vi.advanceTimersByTimeAsync(500));
    rerender({ revision: 2 });
    await act(() => vi.advanceTimersByTimeAsync(500));
    expect(saveGraph).toHaveBeenCalledTimes(1);
    await act(async () => { first(); await Promise.resolve(); });
    expect(saveGraph).toHaveBeenCalledTimes(2);
    expect(status).not.toHaveBeenCalledWith("saved");
    await act(async () => { second(); await result.current(); });
    expect(status).toHaveBeenLastCalledWith("saved");
    await act(async () => { await result.current(); await result.current(); });
    expect(saveGraph).toHaveBeenCalledTimes(2);
});
it("retries a failed save and flushes the latest edit on unmount", async () => {
    vi.mocked(saveGraph).mockRejectedValueOnce(new Error("offline"));
    const status = vi.fn();
    const { result, rerender, unmount } = renderHook(({ revision }) => useGraphAutosave("id", graph(revision * 16), revision, true, status), { initialProps: { revision: 1 } });
    await act(() => vi.advanceTimersByTimeAsync(500));
    expect(status).toHaveBeenLastCalledWith("error");
    await act(async () => { await result.current(); });
    expect(status).toHaveBeenLastCalledWith("saved");
    rerender({ revision: 2 }); unmount();
    await act(async () => { await Promise.resolve(); });
    expect(saveGraph).toHaveBeenLastCalledWith("id", graph(32));
    expect(saveGraph).toHaveBeenCalledTimes(3);
});
